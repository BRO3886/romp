#!/usr/bin/env python3
"""Generate wire records from the versioned daemon JSON Schema."""
import json
import pathlib
import subprocess

root = pathlib.Path(__file__).resolve().parent.parent
schema = json.loads((root / "docs/protocol/v1.schema.json").read_text())


def field_name(name):
    return "".join(part.capitalize() for part in name.split("_"))


def go_type(prop):
    if "x-go-type" in prop:
        return prop["x-go-type"]
    if "$ref" in prop:
        return ("*" if prop.get("x-go-pointer") else "") + prop["$ref"].split("/")[-1]
    kind = prop["type"]
    if kind == "array":
        return "[]" + go_type(prop["items"])
    return {"string": "string", "integer": "int", "boolean": "bool"}[kind]


def swift_type(prop):
    if "x-swift-type" in prop:
        return prop["x-swift-type"]
    if "$ref" in prop:
        return prop["$ref"].split("/")[-1]
    kind = prop["type"]
    if kind == "array":
        return "[" + swift_type(prop["items"]) + "]"
    return {"string": "String", "integer": "Int", "boolean": "Bool"}[kind]


go = ["// Code generated by scripts/generate_protocol.py. DO NOT EDIT.",
      "package protocol", 'import "encoding/json"',
      *[f'import "{package}"' for package in schema.get("x-go-imports", [])]]
swift = ["// Code generated by scripts/generate_protocol.py. DO NOT EDIT.",
         "import Foundation"]
for name, definition in schema["$defs"].items():
    go.append(f"type {name} struct {{")
    swift.append(f"public struct {name}: Codable {{")
    keys = []
    for field, prop in definition["properties"].items():
        optional = field not in definition.get("required", [])
        go_field = prop.get("x-go-field", field_name(field))
        tag = field + (",omitempty" if optional else "")
        go.append(f' {go_field} {go_type(prop)} `json:"{tag}"`')
        swift_field = field_name(field)
        swift_field = swift_field[0].lower() + swift_field[1:]
        swift.append(f' public var {swift_field}: {swift_type(prop)}' + ("?" if optional else ""))
        keys.append(f' case {swift_field} = "{field}"')
    go.append("}")
    swift.extend([" enum CodingKeys: String, CodingKey {", *keys, " }", "}"])

swift.append("""
public enum JSONValue: Codable {
 case null, bool(Bool), number(Double), string(String)
 case array([JSONValue]), object([String: JSONValue])
 public init(from decoder: Decoder) throws {
  let c = try decoder.singleValueContainer()
  if c.decodeNil() { self = .null }
  else if let v = try? c.decode(Bool.self) { self = .bool(v) }
  else if let v = try? c.decode(Double.self) { self = .number(v) }
  else if let v = try? c.decode(String.self) { self = .string(v) }
  else if let v = try? c.decode([JSONValue].self) { self = .array(v) }
  else { self = .object(try c.decode([String: JSONValue].self)) }
 }
 public func encode(to encoder: Encoder) throws {
  var c = encoder.singleValueContainer()
  switch self {
  case .null: try c.encodeNil()
  case .bool(let v): try c.encode(v)
  case .number(let v): try c.encode(v)
  case .string(let v): try c.encode(v)
  case .array(let v): try c.encode(v)
  case .object(let v): try c.encode(v)
  }
 }
}
""")
go_path = root / "internal/protocol/types_generated.go"
go_path.write_text("\n".join(go) + "\n")
subprocess.run(["gofmt", "-w", str(go_path)], check=True)
(root / "docs/protocol/Types.generated.swift").write_text("\n".join(swift).rstrip() + "\n")
